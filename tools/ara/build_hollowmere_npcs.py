#!/usr/bin/env python3
"""Build the first Hollowmere cast from the pinned Ara 3D Gen checkout.

Run from the Ara repository after setup-assets and the Silverhart under-layer patch:
  python "$GITHUB_WORKSPACE/tools/ara/build_hollowmere_npcs.py" \
    --out "$GITHUB_WORKSPACE/art/characters/hollowmere"

Each profile is a complete, deterministic Ara export. No hand-built or
substitute human meshes are generated by this script.
"""
import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROFILE_FILE = ROOT / "data" / "characters" / "hollowmere_npcs.json"
ARA_ROOT = Path.cwd()

KNOWN_HAIR = {
    "braid01", "short02", "short03", "short04", "long01", "bob02",
    "buzz", "cornrows", "box_braids", "mohawk", "none",
}
KNOWN_SHOES = {"none", "sandals", "combat_boots"}
KNOWN_EYES_FALLBACK = {
    "blackbrown", "darkbrown", "brown", "brownlight", "green",
    "bluegreen", "grey", "blue", "lightblue", "deepblue", "ice",
}
KNOWN_TATTOOS_FALLBACK = {
    "armband_l", "sleeve_r", "forearm_l", "chest", "back", "face_marks",
}
KNOWN_WEAPONS_FALLBACK = {"none", "rifle", "pistol", "sword", "knife"}
KNOWN_CARRY_FALLBACK = {"none", "straw_tote", "handbag", "briefcase", "backpack"}


def source_ids(path: str, pattern: str) -> set[str]:
    file = ARA_ROOT / path
    if not file.exists():
        return set()
    return set(re.findall(pattern, file.read_text()))


def validate_profiles(profiles: dict) -> None:
    garments = source_ids("src/core/garments/catalog.ts", r"\bid:\s*'([^']+)'")
    garments.add("none")
    # The Silverhart patch adds this exact under-layer ID to Ara's catalogue.
    garments.add("bra")
    eyes = source_ids("src/app/ui/quick-data.ts", r"\['([^']+)',\s*'[^']+',\s*'#[0-9a-fA-F]{6}'\]")
    tattoos = source_ids("src/core/looks/tattoos.ts", r"'(armband_l|sleeve_r|forearm_l|chest|back|face_marks)'")
    weapons = source_ids("src/core/props/weapons.ts", r"'(none|rifle|pistol|sword|knife)'")
    carry = source_ids("src/core/props/carry.ts", r"'(none|straw_tote|handbag|briefcase|backpack)'")
    facial = source_ids("src/core/looks/hair.ts", r"'(none|stubble|mustache|mustache_stubble|goatee|short_beard|full_beard)'")

    eyes = eyes or KNOWN_EYES_FALLBACK
    tattoos = tattoos or KNOWN_TATTOOS_FALLBACK
    weapons = weapons or KNOWN_WEAPONS_FALLBACK
    carry = carry or KNOWN_CARRY_FALLBACK
    weapons.add("none")
    carry.add("none")
    facial = facial or {"none", "stubble", "mustache", "mustache_stubble", "goatee", "short_beard", "full_beard"}

    seen = set()
    for profile in profiles.get("characters", []):
        character_id = profile.get("id", "")
        if not character_id or character_id in seen:
            raise SystemExit(f"Missing or duplicate character id: {character_id!r}")
        seen.add(character_id)
        params = profile.get("params", {})
        for key in ("gender", "age", "muscle", "weight", "height", "proportions", "african", "asian", "caucasian"):
            value = params.get(key)
            if not isinstance(value, (int, float)) or not 0.0 <= float(value) <= 1.0:
                raise SystemExit(f"{character_id}: Ara slider {key} must be a number from 0 to 1")
        if params.get("eyes") not in eyes:
            raise SystemExit(f"{character_id}: unsupported Ara eye colour {params.get('eyes')!r}")
        if params.get("hair") not in KNOWN_HAIR:
            raise SystemExit(f"{character_id}: unsupported/unchecked Ara hairstyle {params.get('hair')!r}")
        if params.get("facialHair", "none") not in facial:
            raise SystemExit(f"{character_id}: unsupported Ara facial hair")
        for tattoo in params.get("tattoos", []):
            if tattoo not in tattoos:
                raise SystemExit(f"{character_id}: unsupported Ara tattoo {tattoo!r}")
        if params.get("tattoos") and float(params["age"]) < 0.34375:
            raise SystemExit(f"{character_id}: Ara tattoos are adult-only")
        for key in ("top", "underTop", "underBottom", "jacket", "bottom"):
            item = params.get(key, "none")
            if item not in garments:
                raise SystemExit(f"{character_id}: {key} references a garment not in the patched Ara catalogue: {item!r}")
        for item in params.get("accessories", []):
            if item not in garments:
                raise SystemExit(f"{character_id}: unsupported Ara accessory {item!r}")
        if params.get("shoes", "none") not in KNOWN_SHOES:
            raise SystemExit(f"{character_id}: unsupported/unchecked Ara footwear {params.get('shoes')!r}")
        if params.get("weapon", "none") not in weapons:
            raise SystemExit(f"{character_id}: unsupported Ara weapon {params.get('weapon')!r}")
        if params.get("carry", "none") not in carry:
            raise SystemExit(f"{character_id}: unsupported Ara carried prop {params.get('carry')!r}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--detail", choices=("low", "medium", "high"), default=None)
    args = parser.parse_args()

    if not (ARA_ROOT / "package.json").exists() or not (ARA_ROOT / "src").exists():
        raise SystemExit("Run this script from the pinned Ara 3D Gen repository root")
    if not PROFILE_FILE.exists():
        raise SystemExit(f"Missing character profile file: {PROFILE_FILE}")

    manifest = json.loads(PROFILE_FILE.read_text())
    validate_profiles(manifest)
    args.out.mkdir(parents=True, exist_ok=True)

    built = []
    for profile in manifest["characters"]:
        character_id = profile["id"]
        detail = args.detail or profile.get("detail", "medium")
        params = dict(profile["params"])
        params["name"] = profile["name"]
        params["detail"] = detail
        params.setdefault("rig", "game")
        params.setdefault("restPose", "A")
        params.setdefault("animations", True)
        params.setdefault("faceBones", True)
        params.setdefault("faceShapes", True)
        params.setdefault("speechShapes", False)
        params.setdefault("expression", "neutral")

        params_path = args.out / f"{character_id}.params.json"
        params_path.write_text(json.dumps(params, indent=2) + "\n")
        export_dir = args.out / f".{character_id}_export"
        if export_dir.exists():
            shutil.rmtree(export_dir)
        export_dir.mkdir(parents=True)

        print(f"\n=== Ara export: {profile['name']} ({detail}) ===", flush=True)
        subprocess.run([
            "npm", "run", "export", "--",
            "--params", str(params_path),
            "--detail", detail,
            "--formats", "glb",
            "--out", str(export_dir),
        ], cwd=ARA_ROOT, check=True)

        candidates = sorted(export_dir.glob("*.glb"))
        if len(candidates) != 1:
            raise SystemExit(f"{character_id}: expected one GLB, found {len(candidates)}")
        target = args.out / f"{character_id}.glb"
        shutil.copy2(candidates[0], target)
        if target.stat().st_size < 100_000:
            raise SystemExit(f"{character_id}: suspiciously small GLB ({target.stat().st_size:,} bytes)")
        print(f"Built {profile['name']}: {target.stat().st_size:,} bytes", flush=True)
        built.append({
            "id": character_id,
            "game_id": profile["game_id"],
            "name": profile["name"],
            "role": profile["role"],
            "hex": profile["hex"],
            "detail": detail,
            "model": f"{character_id}.glb",
            "params": params,
        })
        shutil.rmtree(export_dir)

    output_manifest = {
        "schema_version": manifest["schema_version"],
        "generator": manifest["generator"],
        "generator_commit": manifest["generator_commit"],
        "characters": built,
    }
    (args.out / "profiles.json").write_text(json.dumps(output_manifest, indent=2) + "\n")
    print(f"\nBuilt {len(built)} Hollowmere Ara characters.", flush=True)


if __name__ == "__main__":
    main()
